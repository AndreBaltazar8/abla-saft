#!/usr/bin/env python3
"""Generates src/codes.ab from the official XSD: the country and currency lists are
too long to copy by hand. Usage: tools/gen-codes.py .sources/saftpt1.04_01.xsd > src/codes.ab"""
import sys
import xml.etree.ElementTree as ET

X = "{http://www.w3.org/2001/XMLSchema}"
root = ET.parse(sys.argv[1]).getroot()


def pattern(kind, name):
    for item in root.findall(X + kind):
        if item.get("name") == name:
            return item.find(f"{X}simpleType/{X}restriction/{X}pattern" if kind == "element" else f"{X}restriction/{X}pattern").get("value")
    raise SystemExit(f"{name} not in the schema")


print("// Generated by tools/gen-codes.py from saftpt1.04_01.xsd. Don't edit.")
print('import "abla/text"\n')
for function, kind, name in (
    ("saftCountryCodes", "element", "Country"),
    ("saftCustomerCountryCodes", "simpleType", "CustomerCountry"),
    ("saftTaxRegionCodes", "element", "TaxCountryRegion"),
    ("saftCurrencyCodes", "element", "CurrencyCode"),
):
    print(f'val {function} = "|{pattern(kind, name)}|"\n')
print('fun saftCodeIn(codes: string, code: string): bool = code != "" && !code.contains("|") && codes.contains("|" + code + "|")')
